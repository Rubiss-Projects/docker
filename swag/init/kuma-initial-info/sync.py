"""Reconcile explicit SWAG labels without replacing or removing Kuma records."""

import argparse
from dataclasses import dataclass
import json
import os

PREFIX = "swag.uptime-kuma.monitor."
DESCRIPTION = "Automatically generated by SWAG auto-uptime-kuma"
RESERVED = {"id", "active", "forceinactive", "tags", "childrenids", "pathname"}


@dataclass
class Change:
    container: str
    monitor_id: int | None
    fields: dict
    group: str | None = None


@dataclass
class Plan:
    changes: list[Change]
    groups: dict[str, int | None]
    retained: int
    tag_id: int | None

    def summary(self):
        # Label values may contain credentials; log field names only.
        return {
            "changes": [{"container": c.container, "id": c.monitor_id,
                         "fields": sorted(c.fields), "parentChange": c.group is not None}
                        for c in self.changes],
            "groupsToCreate": sum(value is None for value in self.groups.values()),
            "retainedAbsentMonitors": self.retained,
        }


def label_fields(labels):
    fields = {}
    for label, raw in labels.items():
        if not label.startswith(PREFIX):
            continue
        key = label[len(PREFIX):]
        if not key or key.lower() in RESERVED:
            raise ValueError("SWAG labels cannot control monitor identity or pause state")
        if key in ("accepted_statuscodes", "notificationIDList"):
            value = [item.strip() for item in raw.split(",") if item.strip()]
            if key == "notificationIDList":
                value = sorted({int(item) for item in value})
        else:
            value = int(raw) if raw.isdigit() else raw
        fields[key] = value
    return fields


def tagged_records(monitors):
    records = {"group": {}, "monitor": {}}
    for monitor in monitors:
        tags = [tag for tag in monitor.get("tags", []) if tag.get("name") == "swag"]
        if len(tags) > 1:
            raise ValueError("Multiple SWAG tags on one monitor; reconcile manually")
        if not tags:
            continue
        key = tags[0].get("value", "").lower()
        kind = "group" if monitor["type"] == "group" else "monitor"
        if not key or key in records[kind]:
            raise ValueError("Ambiguous SWAG monitor identity; reconcile manually")
        records[kind][key] = monitor
    return records


def build_plan(api, containers, domain):
    """Read actual monitor details; the upstream config cache is not authoritative."""
    monitors = api.get_monitors()
    records = tagged_records(monitors)
    tags = [tag for tag in api.get_tags() if tag["name"] == "swag"]
    if len(tags) > 1:
        raise ValueError("Ambiguous SWAG tag definition")
    default_notifications = sorted({n["id"] for n in api.get_notifications() if n.get("isDefault")})
    groups = {}
    changes = []
    seen = set()
    for container in sorted(containers, key=lambda c: c.name):
        key = container.name.lower()
        if key in seen:
            raise ValueError("Duplicate container name")
        seen.add(key)
        fields = label_fields(container.labels)
        if fields.get("type") == "group":
            raise ValueError("Container monitors cannot be groups")
        existing = records["monitor"].get(key)
        current = api.get_monitor(existing["id"]) if existing else None
        group = None
        if "parent" in fields:
            parent = fields["parent"]
            if isinstance(parent, int):
                if not any(m["id"] == parent and m["type"] == "group" for m in monitors):
                    raise ValueError("Numeric parent must identify an existing group")
            elif not parent:
                fields["parent"] = None
            else:
                tagged = records["group"].get(parent.lower())
                matches = [m for m in monitors if m["type"] == "group" and m["name"].lower() == parent.lower()]
                if len(matches) > 1 or (tagged and matches and tagged["id"] != matches[0]["id"]):
                    raise ValueError("Ambiguous parent group")
                found = tagged or (matches[0] if matches else None)
                # Keep group keys case-insensitive, retaining the label's display name.
                group = next((name for name in groups if name.lower() == parent.lower()), parent)
                groups[group] = found["id"] if found else None
                del fields["parent"]
                if found and current and current.get("parent") == found["id"]:
                    group = None
        if current:
            fields = {name: value for name, value in fields.items() if current.get(name) != value}
        else:
            fields = {"type": "http", "name": container.name.title(),
                      "url": f"https://{container.name}.{domain}", "description": DESCRIPTION,
                      "notificationIDList": default_notifications, **fields}
            if any(m["name"].lower() == fields["name"].lower() for m in monitors):
                raise ValueError("An unlinked monitor already has the requested name; reconcile manually")
            if any(c.monitor_id is None and c.fields["name"].lower() == fields["name"].lower() for c in changes):
                raise ValueError("Multiple new monitors request the same name")
        if fields or group is not None:
            changes.append(Change(container.name, current["id"] if current else None, fields, group))
    retained = len(set(records["monitor"]) - seen)
    return Plan(changes, groups, retained, tags[0]["id"] if tags else None)


def apply_plan(api, plan):
    """Only add and edit. An interrupted add/tag pair remains for manual reconciliation."""
    tag_id = plan.tag_id
    if tag_id is None and (plan.changes or any(value is None for value in plan.groups.values())):
        tag_id = api.add_tag(name="swag", color="#5cdd8b")["id"]
    groups = dict(plan.groups)
    for name, monitor_id in groups.items():
        if monitor_id is None:
            monitor_id = api.add_monitor(type="group", name=name, description=DESCRIPTION)["monitorID"]
            api.add_monitor_tag(tag_id=tag_id, monitor_id=monitor_id, value=name.lower())
            groups[name] = monitor_id
    for change in plan.changes:
        fields = dict(change.fields)
        if change.group is not None:
            fields["parent"] = groups[change.group]
        if change.monitor_id is None:
            monitor_id = api.add_monitor(**fields)["monitorID"]
            api.add_monitor_tag(tag_id=tag_id, monitor_id=monitor_id, value=change.container.lower())
        else:
            # The SDK fetches full details before merging these fields. Omitting active
            # and unspecified notification choices preserves the actual saved settings.
            response = api.edit_monitor(change.monitor_id, **fields)
            if response.get("monitorID") != change.monitor_id:
                raise RuntimeError("Kuma did not confirm the original monitor ID")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    # Imports stay here so focused planning tests need neither Docker nor a server.
    import fcntl
    import docker
    from auto_uptime_kuma.uptime_kuma_service import InitialInfoUptimeKumaApi

    with open("/run/lock/kuma-history-sync.lock", "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        client = docker.from_env()
        api = None
        try:
            containers = client.containers.list(filters={"label": "swag.uptime-kuma.enabled=true"})
            api = InitialInfoUptimeKumaApi(os.environ["UPTIME_KUMA_URL"])
            api.login(os.environ["UPTIME_KUMA_USERNAME"], os.environ["UPTIME_KUMA_PASSWORD"])
            plan = build_plan(api, containers, os.environ["URL"])
            print(json.dumps({"dryRun": args.dry_run, **plan.summary()}), flush=True)
            if not args.dry_run:
                apply_plan(api, plan)
                print("[kuma-history-sync] Reconciliation complete; existing records retained", flush=True)
        finally:
            if api is not None:
                api.disconnect()
            client.close()


if __name__ == "__main__":
    main()
